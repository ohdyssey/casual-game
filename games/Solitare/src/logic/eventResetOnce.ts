/**
 * eventResetOnce.ts — **이벤트 1회 강제 리셋**(PO 2026-08-24 "이벤트 리셋하세요").
 *
 * 세이브는 플레이어 브라우저에 있어 개발자가 직접 지울 수 없다. 그래서 태그를 하나 두고,
 * 저장된 태그가 최신이 아니면 **부팅 때 한 번** 이벤트만 초기화한다. 이미 리셋한 기기는
 * 태그가 같아 두 번 지우지 않는다.
 *
 * ⚠️ 코인·다이아·레벨·건설·컬렉션은 건드리지 않는다 — 지우는 목록은 `eventReset.ts` 단일 출처.
 * ⚠️ 다시 한 번 전체 리셋이 필요하면 **태그 문자열만 바꾼다**(날짜-일련번호 규칙).
 */
import { loadSave, writeSave } from '../save.js';
import { resetAllEvents } from './eventReset.js';

/**
 * 지금 배포의 리셋 태그 — 바꾸면 모든 기기가 부팅 때 한 번 더 이벤트를 초기화한다.
 *
 * `b`(2026-08-24): 위클리 목표 단위가 **판 수 → 상품 개수**로 확정되고 목표가 90 → 2,800 으로
 *   바뀌었다. 옛 단위로 쌓인 진행도는 의미가 없어(4판이면 완주 상태였다) 한 번 더 비운다.
 * `c`(2026-08-24): 투데이 리그가 **10단계 톱니바퀴 + 그랜드 프라이즈**로 바뀌었다. 직전 구조에서
 *   이미 완주(stage 10) 상태인 세이브는 단계 보상을 한 번도 볼 수 없으므로 사다리를 다시 세운다.
 * `d`(2026-08-24): 리그 단계 목표를 100 → 180별로 올렸다(1단계 1 → 8). 옛 목표로 쌓인 진행도는
 *   새 사다리와 뜻이 달라 그대로 두면 첫 칸이 이미 넘쳐 있다.
 * `e`(2026-08-24): 리그 목표를 다시 **1단계 10 → 10단계 300**(합계 931)으로 지정받았다.
 */
export const EVENT_RESET_TAG = '2026-08-24e';

/** 아직 이 태그로 리셋하지 않았으면 이벤트를 초기화한다. 실제로 리셋했으면 true. */
export function resetEventsOnce(): boolean {
  const save = loadSave();
  if (save.eventResetTag === EVENT_RESET_TAG) return false;
  writeSave({ ...resetAllEvents(save), eventResetTag: EVENT_RESET_TAG });
  return true;
}
